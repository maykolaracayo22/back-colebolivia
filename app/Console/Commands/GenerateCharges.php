<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use App\Models\Student;
use App\Models\StudentAccount;
use App\Models\AccountCharge;
use App\Models\FeeConfig;
use App\Models\Enrollment;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;

class GenerateCharges extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'charges:generate
                            {year : AÃ±o acadÃ©mico para generar cargos}
                            {--student= : ID especÃ­fico de estudiante (opcional)}
                            {--nivel= : Nivel especÃ­fico: inicial, primaria, secundaria (opcional)}
                            {--grado= : Grado especÃ­fico (opcional)}
                            {--dry-run : Simular sin guardar cambios}';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Generar cargos financieros (matrÃ­cula + mensualidades) para estudiantes activos';

    /**
     * Execute the console command.
     */
    public function handle()
    {
        $year = (int) $this->argument('year');
        $studentId = $this->option('student');
        $nivel = $this->option('nivel');
        $grado = $this->option('grado');
        $dryRun = $this->option('dry-run');

        $this->info("ðŸ”„ Generando cargos para el aÃ±o {$year}...");

        if ($dryRun) {
            $this->warn("âš ï¸  Modo DRY-RUN: No se guardarÃ¡n cambios");
        }

        // Obtener estudiantes segÃºn filtros
        $query = Student::query()->where('estado', 'activo');

        if ($studentId) {
            $query->where('id', $studentId);
            $this->info("ðŸ“Œ Filtro: Estudiante ID {$studentId}");
        }

        if ($nivel) {
            $query->where('nivel', $nivel);
            $this->info("ðŸ“Œ Filtro: Nivel {$nivel}");
        }

        if ($grado) {
            $query->where('grado', $grado);
            $this->info("ðŸ“Œ Filtro: Grado {$grado}");
        }

        $students = $query->get();

        if ($students->isEmpty()) {
// Code generated by MCHP Chatbot
            $this->error("âŒ No se encontraron estudiantes con los filtros especificados");
            return Command::FAILURE;
        }

        $this->info("ðŸ“Š Estudiantes encontrados: " . $students->count());

        // Verificar configuraciones de tarifas
        $feeConfigs = FeeConfig::where('year', $year)->get();

        if ($feeConfigs->isEmpty()) {
            $this->error("âŒ No hay configuraciones de tarifas (FeeConfig) para el aÃ±o {$year}");
            $this->info("ðŸ’¡ Sugerencia: Crear FeeConfig antes de ejecutar este comando");
            return Command::FAILURE;
        }

        $this->info("ðŸ’° Configuraciones de tarifas encontradas: " . $feeConfigs->count());

        $processed = 0;
        $skipped = 0;
        $errors = 0;

        $progressBar = $this->output->createProgressBar($students->count());
        $progressBar->start();

        foreach ($students as $student) {
            try {
                // Verificar si ya tiene cuenta para este aÃ±o
                $account = StudentAccount::where('student_id', $student->id)
                    ->where('year', $year)
                    ->first();

                if ($account) {
                    // Verificar si ya tiene cargos
                    $existingCharges = $account->accountCharges()->count();

                    if ($existingCharges > 0) {
                        $skipped++;
                        $progressBar->advance();
                        continue;
                    }
                }

                if (!$dryRun) {
                    DB::beginTransaction();
                }

                // Crear o obtener cuenta
                if (!$account) {
                    if (!$dryRun) {
                        $account = StudentAccount::create([
                            'student_id' => $student->id,
                            'year' => $year,
                            'total_debt' => 0,
                            'total_paid' => 0,
                            'status' => 'PENDIENTE'
                        ]);
                    } else {
                        $account = new StudentAccount([
                            'student_id' => $student->id,
                            'year' => $year
                        ]);
                        $account->id = 999999; // ID ficticio para dry-run
                    }
                }

                // Obtener configuraciÃ³n de tarifa segÃºn nivel del estudiante
                $feeConfig = $feeConfigs->where('nivel', $student->nivel)->first();

                if (!$feeConfig) {
                    $this->warn("âš ï¸  No hay FeeConfig para nivel '{$student->nivel}' del estudiante {$student->id}");
                    $skipped++;
                    $progressBar->advance();
                    continue;
                }

                $totalDebt = 0;

                // 1. Generar cargo de MATRÃCULA
                $matriculaAmount = $feeConfig->matricula_amount ?? 500;
                $matriculaDueDate = "{$year}-01-31";

                if (!$dryRun) {
                    AccountCharge::create([
                        'student_account_id' => $account->id,
                        'concept' => 'MATRICULA',
                        'description' => "MatrÃ­cula aÃ±o {$year}",
                        'amount' => $matriculaAmount,
                        'paid_amount' => 0,
                        'status' => 'PENDING',
                        'due_date' => $matriculaDueDate,
                        'created_by' => null // Sistema
                    ]);
                }

                $totalDebt += $matriculaAmount;

                // 2. Generar 10 cargos de MENSUALIDAD (febrero a noviembre)
                $mensualidadAmount = $feeConfig->mensualidad_amount ?? 300;

                for ($month = 2; $month <= 11; $month++) {
                    $monthName = $this->getMonthName($month);
                    $dueDay = 10; // Vencimiento dÃ­a 10 de cada mes
                    $dueDate = "{$year}-" . str_pad($month, 2, '0', STR_PAD_LEFT) . "-{$dueDay}";

                    if (!$dryRun) {
                        AccountCharge::create([
                            'student_account_id' => $account->id,
                            'concept' => 'MENSUALIDAD',
                            'description' => "Mensualidad {$monthName} {$year}",
                            'amount' => $mensualidadAmount,
                            'paid_amount' => 0,
                            'status' => 'PENDING',
                            'due_date' => $dueDate,
                            'created_by' => null
                        ]);
                    }

                    $totalDebt += $mensualidadAmount;
                }

                // Actualizar total_debt de la cuenta
                if (!$dryRun) {
                    $account->total_debt = $totalDebt;
                    $account->save();

                    DB::commit();
                }

                $processed++;

            } catch (\Exception $e) {
                if (!$dryRun) {
                    DB::rollBack();
                }

                Log::error("Error generando cargos para estudiante {$student->id}: " . $e->getMessage());
                $errors++;
            }

            $progressBar->advance();
        }

        $progressBar->finish();
        $this->newLine(2);

        // Resumen
        $this->info("âœ… Proceso completado");
        $this->table(
            ['MÃ©trica', 'Cantidad'],
            [
                ['Estudiantes procesados', $processed],
                ['Estudiantes omitidos (ya tienen cargos)', $skipped],
                ['Errores', $errors],
                ['Total estudiantes', $students->count()]
            ]
        );

        if ($processed > 0) {
            $chargesPerStudent = 11; // 1 matrÃ­cula + 10 mensualidades
            $totalChargesCreated = $processed * $chargesPerStudent;

            $this->info("ðŸ“‹ Total de cargos generados: {$totalChargesCreated}");
        }

        if ($dryRun) {
            $this->warn("âš ï¸  Modo DRY-RUN: No se guardaron cambios. Ejecutar sin --dry-run para aplicar.");
        }

        return Command::SUCCESS;
    }

    /**
     * Obtener nombre del mes en espaÃ±ol
     */
    private function getMonthName($month): string
    {
        $months = [
            1 => 'Enero', 2 => 'Febrero', 3 => 'Marzo', 4 => 'Abril',
            5 => 'Mayo', 6 => 'Junio', 7 => 'Julio', 8 => 'Agosto',
            9 => 'Septiembre', 10 => 'Octubre', 11 => 'Noviembre', 12 => 'Diciembre'
        ];

        return $months[$month] ?? 'Mes ' . $month;
    }
}
